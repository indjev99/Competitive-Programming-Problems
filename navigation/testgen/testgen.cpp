Graph genGraph(const TestSpec& testSpec)
{
    if (testSpec.isExample) return genExampleGraph();

    int n = testSpec.n;

    Graph g;

    g.n = n;
    g.adj.resize(n);
    g.start = 0;

    std::vector<std::pair<int, double>> cycleSizeProbs = testSpec.cycleSizeProbs;
    double sharedParNodeProb = testSpec.sharedParNodeProb;
    int parCycleMode = testSpec.parCycleMode;
    int parNodeMode = testSpec.parNodeMode;
    bool doAppleCycle = testSpec.doAppleCycle && parNodeMode == PNM_APPLES;
    int start = testSpec.start;
    std::vector<bool> revCycles = testSpec.revCycles;
    bool shuffleAdj = testSpec.shuffleAdj;
    bool revAdj = testSpec.revAdj;
    bool extractStart = testSpec.extractStart;
    int maxDegree = testSpec.maxDegree;

    if (extractStart)
    {
        n--;
    }

    int numEdges = 0;
    std::vector<std::vector<int>> cycles;
    std::vector<int> cyclePars;

    int currNode = 0;

    while (currNode < n)
    {
        int cycleSize = selectCycleSize(cycleSizeProbs);

        int parentCycle = -1;
        if (!cycles.empty())
        {
            if (parCycleMode == PCM_RNG) parentCycle = randNum(0, cycles.size());
            else if (parCycleMode == PCM_STAR) parentCycle = 0;
            else if (parCycleMode == PCM_PATH) parentCycle = cycles.size() - 1;
            else
            {
                std::cerr << "ERROR: Invalid: parCycleMode = " << parCycleMode << std::endl;
                exit(0);
            }
        }

        int parentNode = -1;
        if (parentCycle != -1)
        {
            int parentNodeIdx = -1;
            if (parNodeMode == PNM_RNG) parentNodeIdx = randNum(0, cycles[parentCycle].size());
            else if (parNodeMode == PNM_APPLES) parentNodeIdx = 0;
            else if (parNodeMode == PNM_BEADS) parentNodeIdx = cycles[parentCycle].size() / 2;
            else
            {
                std::cerr << "ERROR: Invalid: parNodeMode = " << parNodeMode << std::endl;
                exit(0);
            }
            parentNode = cycles[parentCycle][parentNodeIdx];
        }

        bool shareParNode = false;
        if (parentCycle != -1 && cycles[parentCycle].size() > 1 && cycleSize > 1)
        {
            shareParNode = randReal(0, 1) < sharedParNodeProb;
        }

        cycleSize = std::min(cycleSize, n - currNode + shareParNode);
        if (cycleSize == 2) cycleSize = 1;

        if (cycleSize == 1) shareParNode = false;

        if (maxDegree != -1 && parentNode != -1)
        {
            int newDegree = g.adj[parentNode].size();
            if (shareParNode) newDegree += 2;
            else newDegree += 1;
            if (newDegree > maxDegree) continue;
        }

        if (!shareParNode) cyclePars.push_back(parentCycle);
        else cyclePars.push_back(cyclePars[parentCycle]);

        cycles.push_back({});
        for (int i = 0; i < cycleSize; i++)
        {
            int node = -1;
            if (i == 0 && shareParNode) node = parentNode;
            else node = currNode++;
            cycles.back().push_back(node);
        }

        if (parentNode != -1 && !shareParNode)
        {
            numEdges++;
            g.adj[parentNode].push_back(cycles.back().front());
            g.adj[cycles.back().front()].push_back(parentNode);
        }

        if (cycleSize > 1)
        {
            for (int i = 0; i < cycleSize; i++)
            {
                numEdges++;
                int a = cycles.back()[(i + 1) % cycleSize];
                int b = cycles.back()[(i - 1 + cycleSize) % cycleSize];
                if (!revCycles.empty() && revCycles[i % revCycles.size()])
                {
                    std::swap(a, b);
                }
                g.adj[cycles.back()[i]].push_back(a);
                g.adj[cycles.back()[i]].push_back(b);
            }
        }
    }

    if (doAppleCycle && cycles.back().front() != cycles.front().front() && cycles[cyclePars.back()].front() != cycles.front().front())
    {
        numEdges++;
        g.adj[cycles.back().front()].push_back(cycles.front().front());
        g.adj[cycles.front().front()].push_back(cycles.back().front());

        int curr = cycles.size() - 1;

        cycles.push_back({});
        while (curr != -1)
        {
            cycles.back().push_back(cycles[curr].front());
            curr = cyclePars[curr];
        }
    }

    std::vector<bool> inCycle(n, false);

    int numCycles = 0;
    for (int i = 0; i < (int) cycles.size(); i++)
    {
        if (cycles[i].size() == 1) continue;

        numCycles++;

        for (int u : cycles[i])
        {
            inCycle[u] = true;
        }
    }

    int numSingles = 0;
    for (int i = 0; i < n; i++)
    {
        if (!inCycle[i]) numSingles++;
    }

    if (start == -1)
    {
        g.start = randNum(0, n);

        if (maxDegree != -1 && extractStart)
        {
            while ((int) g.adj[g.start].size() >= maxDegree)
            {
                g.start = randNum(0, n);
            }
        }
    }
    else g.start = start;

    if (extractStart)
    {
        numSingles++;
        numEdges++;
        g.adj[g.start].push_back(n);
        g.adj[n].push_back(g.start);
        g.start = n;
        n++;
    }

    int actMaxDegree = 0;
    for (int i = 0; i < n; i++)
    {
        actMaxDegree = std::max(actMaxDegree, (int) g.adj[i].size());
    }

    if (shuffleAdj)
    {
        for (int i = 0; i < n; i++)
        {
            std::shuffle(g.adj[i].begin(), g.adj[i].end(), generator);
        }
    }

    if (revAdj)
    {
        for (int i = 0; i < n; i++)
        {
            std::reverse(g.adj[i].begin(), g.adj[i].end());
        }
    }

    std::cout << "Counts:" << " nodes=" << n << " edges=" << numEdges << " cycles=" << numCycles << " singles=" << numSingles << " maxDegree=" << actMaxDegree << std::endl;

    assert(maxDegree == -1 || actMaxDegree <= maxDegree);
    assert(!extractStart || g.adj[g.start].size() == 1);

    return g;
}

void verifyGraph(const Graph& graph)
{
    assert(graph.n >= 3);
    assert(graph.start >= 0 && graph.start < graph.n);
    assert((int) graph.adj.size() == graph.n);

    std::vector<std::unordered_set<int>> adjSet(graph.n);

    for (int i = 0; i < graph.n; i++)
    {
        for (int other : graph.adj[i])
        {
            assert(other >= 0 && other < graph.n);
            assert(other != i);

            assert(!adjSet[i].count(other));

            adjSet[i].insert(other);
        }
    }

    for (int i = 0; i < graph.n; i++)
    {
        for (int other : graph.adj[i])
        {
            assert(adjSet[other].count(i));
        }
    }
}

void genTest(std::ofstream& outfile, const TestSpec& testSpec)
{
    Graph g = genGraph(testSpec);

    verifyGraph(g);

    outfile << g.n << "\n";
    outfile << g.start << "\n";

    for (int i = 0; i < g.n; i++)
    {
        outfile << g.adj[i].size();
        for (int other : g.adj[i])
        {
            outfile << " " << other;
        }
        outfile << "\n";
    }
}

